import 'dart:io';

import 'package:atom/models/report_model.dart';
import 'package:flutter/services.dart' show rootBundle;
import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

class PdfService {
  static Future<String> generateAndSaveReportPdf(
    List<ReportModel> reports,
    String numberPlate,
    String reportName,
  ) async {
    final pdf = pw.Document();

    // Load logo
    final logoBytes = await rootBundle.load('assets/logo.png');
    final logoImage = pw.MemoryImage(logoBytes.buffer.asUint8List());

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(24),
        build: (pw.Context context) => [
          pw.Center(
            child: pw.Column(
              children: [
                pw.SizedBox(height: 20),
                pw.Text(
                  '$reportName - $numberPlate',
                  style: pw.TextStyle(
                    fontSize: 20,
                    fontWeight: pw.FontWeight.bold,
                  ),
                ),
                pw.SizedBox(height: 10),
                pw.Divider(),
              ],
            ),
          ),
          pw.SizedBox(height: 10),

          /// Report Table
          pw.Table.fromTextArray(
            headers: ['Date', 'Time', 'Speed (km/h)', 'Wire Cut', 'Battery'],
            data: reports.map((r) {
              final date = DateFormat(
                'yyyy-MM-dd',
              ).format(r.createdAt.toLocal());
              final time = DateFormat('hh:mm a').format(r.createdAt.toLocal());
              return [
                date,
                time,
                r.spd,
                r.wr == 1 ? 'Yes' : 'No',
                r.bt == 1 ? 'Disconnected' : 'Connected',
              ];
            }).toList(),
            headerStyle: pw.TextStyle(
              fontWeight: pw.FontWeight.bold,
              color: PdfColors.white,
            ),
            headerDecoration: const pw.BoxDecoration(color: PdfColors.blueGrey),
            cellAlignment: pw.Alignment.center,
            headerAlignment: pw.Alignment.center,
            cellStyle: const pw.TextStyle(fontSize: 10),
            border: null,
          ),

          pw.SizedBox(height: 30),

          /// Footer with generated date and time
          pw.Align(
            alignment: pw.Alignment.centerRight,
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.end,
              children: [
                pw.Text(
                  'Generated on: ${DateFormat('yyyy-MM-dd').format(DateTime.now())}',
                  style: const pw.TextStyle(fontSize: 10),
                ),
                pw.Text(
                  'Time: ${DateFormat('hh:mm a').format(DateTime.now())}',
                  style: const pw.TextStyle(fontSize: 10),
                ),
              ],
            ),
          ),

          pw.SizedBox(height: 20),

          pw.Center(
            child: pw.Column(
              children: [
                pw.Divider(),
                pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.center,
                  children: [
                    pw.Image(logoImage, height: 30),
                    pw.SizedBox(width: 10),
                    pw.Text(
                      'Generated by Atom',
                      style: const pw.TextStyle(
                        fontSize: 10,
                        color: PdfColors.grey600,
                      ),
                    ),
                  ],
                ),
              ],
            ),
          ),
        ],
      ),
    );

    final dir = Directory('/storage/emulated/0/Download');

    if (!await dir.exists()) {
      await dir.create(recursive: true);
    }

    final fileName =
        "${reportName}_${numberPlate}_${DateTime.now().millisecondsSinceEpoch}.pdf";
    final file = File('${dir.path}/$fileName');
    await file.writeAsBytes(await pdf.save());

    return file.path;
  }
}
